/**
 * Shared integration contract between the Martian Outpost Main Survival Loop
 * and the external team modules (Mission/Crew Picker, Rocket Cargo Packer,
 * and Skill Tree Menu).
 */

export type PlanetId = 'mars' | 'moon';
export type ExpeditionId = 'tharsis' | 'radiation' | 'ice' | 'training';

export const CREW_ROLES = ['engineer', 'botanist', 'pilot', 'medic', 'scientist', 'captain'] as const;
export type CrewRole = typeof CREW_ROLES[number];

export type TaskCategory = 'ENG' | 'BIO' | 'NAV' | 'MED' | 'SCI' | 'GOAL';

export type WeatherType = 'Clear' | 'Cold Snap' | 'Dust Haze' | 'Dust Storm' | 'Solar Flare';

export type RationPolicy = 'full' | 'half';

export interface ResourcePool {
    energy: number;   // 0..100+
    food: number;     // daily rations count
    water: number;    // liters / units
    oxygen: number;   // 0..100 %
    res: number;      // general resources / salvage
}

export interface ConditionState {
    radiation: number;     // 0..100 mSv hazard level (100 = lethal)
    weather: WeatherType;
    temperatureC: number;
    morale: number;        // 0..100 %
}

export interface CargoInventory {
    repairKits: number;
    medkits: number;
    batteryPacks: number;
    seedPods: number;
    extraRations: number;
    windSampler: number;   // mission-critical hardware
    waterCanisters?: number;
    oxygenTanks?: number;
    /** Survey instrument for the radiation expedition. */
    radDetector?: number;
    /** Survey instrument for the ice expedition. */
    iceDrill?: number;
}

export type CargoItemId = keyof CargoInventory;

export interface CrewPerk {
    id: string;
    title: string;
    description: string;
    bonusCategory: TaskCategory;
    /** Multiplier applied to task daily resource cost when assigned (e.g., 0.7 = -30% cost). */
    costMultiplier: number;
    /** Extra progress points per Sol on matching tasks (1.0 = normal, 1.5 = 50% faster). */
    speedMultiplier: number;
    /** Output bonus multiplier when completing a matching task. */
    yieldMultiplier: number;
}

export interface CrewMember {
    id: string;
    name: string;
    role: CrewRole;
    trait: string;
    /** What this real astronaut did, in plain words. Every fact comes from `source`. */
    bio: string;
    /** Where the facts in `bio` come from (see docs/CREW.md for the full list). */
    source?: { label: string; url: string };
    portraitPath: string;
    stamina: number;       // 0..100
    health: number;        // 0..100
    morale: number;        // 0..100
    perk: CrewPerk;
    /** Position inside the center outpost viewport (normalized 0..1 inside center stage). */
    stageAnchor: { x: number; y: number };
}

export interface SkillTreeModifiers {
    /** Multiplies daily base food consumption (e.g., 0.75 = 25% less food eaten). */
    foodConsumptionMult: number;
    /** Multiplies daily base oxygen leak/consumption (e.g., 0.75 = 25% less O2 lost). */
    oxygenConsumptionMult: number;
    /** Multiplies daily base water consumption. */
    waterConsumptionMult: number;
    /** Multiplies daily base energy consumption. */
    energyConsumptionMult: number;
    /** Multiplies passive solar generation. */
    solarOutputMult: number;
    /** Multiplies food/O2 generated by Bio tasks. */
    hydroponicsYieldMult: number;
    /** Reduces incoming radiation spikes (0..0.75). */
    radiationShielding: number;
    /** Multiplies negative morale losses (e.g., half rations, crises). */
    moraleDecayMult: number;
    /** Multiplies Rover/Scavenge yields. */
    roverYieldMult: number;
    /** Multiplies AI-generated task resource costs. */
    aiCostDiscountMult: number;
    /** Flat extra task progress per Sol for all crew. */
    taskSpeedBonus: number;
}

export type MissionRequirementKind = 'prep_sensor' | 'prep_rover' | 'prep_supplies' | 'assign_crew';

export interface MissionRequirement {
    id: string;
    label: string;
    kind: MissionRequirementKind;
    current: number;
    target: number;
}

/** Mission goals the survival loop can complete. A goal task wins the mission when its flag matches. */
export const GOAL_FLAGS = [
    'wind_sample_collected', 'ice_core_collected',
    'oxygen_produced', 'crop_harvested', 'radiation_measured',
] as const;
export type GoalFlag = typeof GOAL_FLAGS[number];

export interface MissionGoal {
    id: string;
    title: string;
    description: string;
    coords: string;
    durationHours: number;
    deadlineSol: number;
    requiredFlag: GoalFlag;
    requirements: MissionRequirement[];
    minimumReserves?: Partial<ResourcePool>;
    requiredEquipment?: Partial<Record<CargoItemId, number>>;
    completed: boolean;
}

export interface MissionSetupInput {
    planet: PlanetId;
    targetSol: number;
    missionGoal: MissionGoal;
    rules?: 'tharsis-expedition';
    /** Which expedition profile (src/data/expeditions.ts) the run uses; Tharsis when absent. */
    expedition?: ExpeditionId;
    startingResources: ResourcePool;
    startingConditions: ConditionState;
    cargo: CargoInventory;
    crew: CrewMember[];
    skillModifiers: SkillTreeModifiers;
    /** Purchased nodes to apply to this manifest's base modifiers at run initialization. */
    upgradeIds?: readonly string[];
}

export interface SolSummaryRecord {
    sol: number;
    weather: WeatherType;
    eventTitle: string;
    eventChoiceLabel: string;
    tasksCompleted: string[];
    resourcesAfter: ResourcePool;
    moraleAfter: number;
    radiationAfter: number;
}

export interface MainLoopResult {
    outcome: 'victory' | 'defeat';
    reason: string;
    planet: PlanetId;
    solReached: number;
    targetSol: number;
    goalCompleted: boolean;
    score: number;
    researchPointsEarned: number;
    finalResources: ResourcePool;
    lessons: string[];
    timeline: SolSummaryRecord[];
}

export const UPGRADE_BRANCHES = ['Infrastructure', 'Survival', 'Operations', 'Crew'] as const;
export type UpgradeBranch = typeof UPGRADE_BRANCHES[number];
export type UpgradeTier = 1 | 2 | 3 | 4;

export interface SkillUpgradeDef {
    id: string;
    label: string;
    summary: string;
    branch: UpgradeBranch;
    tier: UpgradeTier;
    slot: 'left' | 'center' | 'right';
    cost: number;
    prerequisites: readonly string[];
    apply: (m: SkillTreeModifiers) => SkillTreeModifiers;
}

export const DEFAULT_SKILL_MODIFIERS: SkillTreeModifiers = {
    foodConsumptionMult: 1.0,
    oxygenConsumptionMult: 1.0,
    waterConsumptionMult: 1.0,
    energyConsumptionMult: 1.0,
    solarOutputMult: 1.0,
    hydroponicsYieldMult: 1.0,
    radiationShielding: 0.0,
    moraleDecayMult: 1.0,
    roverYieldMult: 1.0,
    aiCostDiscountMult: 1.0,
    taskSpeedBonus: 0,
};

type UpgradeEffects = Partial<Omit<SkillTreeModifiers, 'radiationShielding' | 'taskSpeedBonus'>> & {
    radiationShielding?: number;
    taskSpeedBonus?: number;
};

interface UpgradeSpec {
    id: string;
    label: string;
    summary: string;
    effects?: UpgradeEffects;
}

function upgradeBranch(branch: UpgradeBranch, specs: readonly [UpgradeSpec, UpgradeSpec, UpgradeSpec, UpgradeSpec, UpgradeSpec, UpgradeSpec]): SkillUpgradeDef[] {
    const [root, left, right, leftEnd, rightEnd] = specs;
    const tiers = [1, 2, 2, 3, 3, 4] as const;
    const slots = ['center', 'left', 'right', 'left', 'right', 'center'] as const;
    const parents = [[], [root.id], [root.id], [left.id], [right.id], [leftEnd.id, rightEnd.id]];
    const prices = { 1: 3, 2: 5, 3: 7, 4: 10 };
    return specs.map(({ effects, ...spec }, index) => {
        const tier = tiers[index]!;
        return {
            ...spec, branch, tier, slot: slots[index]!, cost: prices[tier], prerequisites: parents[index]!,
            apply(modifiers) {
                if (!effects) return modifiers;
                const next = { ...modifiers };
                for (const key of Object.keys(effects) as Array<keyof SkillTreeModifiers>) {
                    const amount = effects[key]!;
                    const current = modifiers[key];
                    if (key === 'radiationShielding') next[key] = Math.min(0.75, current + amount);
                    else if (key === 'taskSpeedBonus') next[key] = current + amount;
                    else next[key] = current * amount;
                    next[key] = Number(next[key].toFixed(4));
                }
                return next;
            },
        };
    });
}

